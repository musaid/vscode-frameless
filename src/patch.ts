import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {
  allTargets,
  existingWatermarks,
  injectedCss,
  injectedJs,
  injectedWatermark,
  mainJs,
  outDir,
  productJson,
  workbenchHtml,
  type PatchTarget,
} from './paths.js';

export interface TrafficLights {
  readonly x: number;
  readonly y: number;
}

export interface ApplyOptions {
  readonly trafficLights: TrafficLights;
  /** Absolute path of the bundled renderer script (dist/frameless.js). */
  readonly rendererScript: string;
  /** Absolute path of a stylesheet copied into frameless.css; undefined for none. */
  readonly stylesheet: string | undefined;
  /** Absolute path of an image for the empty-editor watermark; undefined keeps the current one. */
  readonly watermark: string | undefined;
}

const MARKER = 'frameless';

/* ---------- pristine sources ---------- */

/** Returns the untouched content of a target, creating the backup on first use. */
const pristine = (t: PatchTarget): string => {
  if (!fs.existsSync(t.bak)) fs.copyFileSync(t.src, t.bak);
  return fs.readFileSync(t.bak, 'utf8');
};

export const isPatched = (): boolean =>
  fs.existsSync(workbenchHtml.src) && fs.readFileSync(workbenchHtml.src, 'utf8').includes(MARKER);

export const hasBackups = (): boolean => allTargets.some((t) => fs.existsSync(t.bak));

/** Backups from a previous VS Code build must not be restored over a new one. */
export const dropBackups = (): void => {
  for (const t of allTargets) if (fs.existsSync(t.bak)) fs.rmSync(t.bak);
};

/* ---------- main.js (Electron BrowserWindow options) ---------- */

// VS Code builds the BrowserWindow options as one object literal in the minified main bundle.
// `experimentalDarkMode` is a stable key in that literal, so we append our keys right after it.
const MAIN_ANCHOR = /experimentalDarkMode:!0/;

const patchMain = (source: string, lights: TrafficLights): string => {
  // The values are spliced into main-process code; anything but a plain number is rejected.
  if (!Number.isFinite(lights.x) || !Number.isFinite(lights.y)) {
    throw new Error('frameless.trafficLights needs numbers for x and y.');
  }
  if (!MAIN_ANCHOR.test(source)) {
    throw new Error(`This VS Code version isn't supported yet: ${mainJs.src} has changed.`);
  }
  // `hidden`, not `hiddenInset`: hiddenInset adds an NSToolbar, and macOS 26 draws toolbar windows
  // with a larger corner radius. trafficLightPosition places the lights either way.
  const injected = `titleBarStyle:"hidden",trafficLightPosition:{x:${lights.x},y:${lights.y}}`;
  return source.replace(MAIN_ANCHOR, (m) => `${m},${injected}`);
};

/* ---------- workbench.html ---------- */

const HTML_ANCHOR = '<script src="./workbench.js" type="module"></script>';

const patchHtml = (source: string): string => {
  if (!source.includes(HTML_ANCHOR)) {
    throw new Error(`This VS Code version isn't supported yet: ${workbenchHtml.src} has changed.`);
  }
  const tags = [
    `<!-- ${MARKER} -->`,
    `<link rel="stylesheet" href="./frameless.css">`,
    `<script src="./frameless.js"></script>`,
  ].join('\n\t');
  return source.replace(HTML_ANCHOR, `${HTML_ANCHOR}\n\t${tags}`);
};

// Images the workbench can render; the extension also decides the MIME type it's served with.
const WATERMARK_TYPES: readonly string[] = ['.svg', '.png', '.jpg', '.jpeg', '.webp'];

const assertFile = (setting: string, file: string | undefined, types: readonly string[]): void => {
  if (file === undefined) return;
  if (!fs.existsSync(file) || !fs.statSync(file).isFile()) {
    throw new Error(`Can't find ${file} (${setting}).`);
  }
  if (!types.includes(path.extname(file).toLowerCase())) {
    throw new Error(`${setting} has to be a ${types.join(', ').replace(/, ([^,]+)$/, ' or $1')} file.`);
  }
};

/** Copies the watermark next to workbench.html; returns its file name, or undefined if none is set. */
const installWatermark = (image: string | undefined): string | undefined => {
  for (const f of existingWatermarks()) fs.rmSync(f);
  if (image === undefined) return undefined;
  const dest = injectedWatermark(path.extname(image).toLowerCase());
  fs.copyFileSync(image, dest);
  return path.basename(dest);
};

const buildCss = (stylesheet: string | undefined, lights: TrafficLights, watermark: string | undefined): string =>
  [
    `/* generated by ${MARKER} */`,
    `:root { --frameless-traffic-x: ${lights.x}px; }`,
    ...(stylesheet === undefined ? [] : ['', fs.readFileSync(stylesheet, 'utf8')]),
    // After the stylesheet, so it beats any `.letterpress` rule in there.
    ...(watermark === undefined ? [] : [`.letterpress { background-image: url("./${watermark}") !important; }`]),
  ].join('\n');

/* ---------- product.json checksums ---------- */

const checksum = (file: string): string =>
  createHash('sha256').update(fs.readFileSync(file)).digest('base64').replace(/=+$/, '');

interface Product {
  checksums?: Record<string, string>;
}

const patchProduct = (source: string): string => {
  const product = JSON.parse(source) as Product;
  for (const relative of Object.keys(product.checksums ?? {})) {
    const abs = path.join(outDir, relative);
    if (fs.existsSync(abs)) product.checksums![relative] = checksum(abs);
  }
  return JSON.stringify(product, null, '\t');
};

/* ---------- manifest for the uninstall hook ---------- */

/** Written at apply time; `uninstall.ts` runs with no `vscode` API and reads this instead. */
export const manifestPath = path.join(os.homedir(), '.frameless', 'manifest.json');

export interface Manifest {
  readonly restore: readonly { src: string; bak: string }[];
  readonly remove: readonly string[];
}

const writeManifest = (): void => {
  const manifest: Manifest = {
    restore: allTargets.map(({ src, bak }) => ({ src, bak })),
    remove: [injectedJs, injectedCss, ...existingWatermarks()],
  };
  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
};

/* ---------- foreign patchers ---------- */

// custom-ui-style patches the same files. On top of it, its Electron keys land after ours in the
// options literal (and win), and its patched files would be backed up as our "pristine" copies.
const FOREIGN_BACKUP = 'custom-ui-style';
const FOREIGN_HTML = 'External Script Start';
const CUSTOM_UI_STYLE_APPLIED =
  'Custom UI Style is still applied. Run its "Rollback, cleanup and restart instantly", then uninstall it.';

const assertNoForeignPatch = (): void => {
  const dirs = new Set(allTargets.map((t) => path.dirname(t.src)));
  const leftovers = [...dirs].flatMap((d) =>
    fs.readdirSync(d).filter((f) => f.includes(FOREIGN_BACKUP)).map((f) => path.join(d, f)),
  );
  if (leftovers.length > 0) {
    throw new Error(CUSTOM_UI_STYLE_APPLIED);
  }
  if (fs.readFileSync(workbenchHtml.src, 'utf8').includes(FOREIGN_HTML)) {
    throw new Error(CUSTOM_UI_STYLE_APPLIED);
  }
};

/* ---------- public ---------- */

export const apply = (opts: ApplyOptions): void => {
  assertNoForeignPatch();
  assertFile('frameless.stylesheet', opts.stylesheet, ['.css']);
  assertFile('frameless.watermark', opts.watermark, WATERMARK_TYPES);
  // Build every patched file before writing any, so a failed check leaves the install untouched.
  const main = patchMain(pristine(mainJs), opts.trafficLights);
  const html = patchHtml(pristine(workbenchHtml));
  fs.writeFileSync(mainJs.src, main);
  fs.writeFileSync(workbenchHtml.src, html);
  fs.copyFileSync(opts.rendererScript, injectedJs);
  const watermark = installWatermark(opts.watermark);
  fs.writeFileSync(injectedCss, buildCss(opts.stylesheet, opts.trafficLights, watermark));
  // Must run last: checksums cover the files patched above.
  fs.writeFileSync(productJson.src, patchProduct(pristine(productJson)));
  writeManifest();
};

export const restore = (): void => {
  for (const t of allTargets) {
    if (!fs.existsSync(t.bak)) continue;
    fs.copyFileSync(t.bak, t.src);
    fs.rmSync(t.bak);
  }
  for (const f of [injectedJs, injectedCss, ...existingWatermarks()]) if (fs.existsSync(f)) fs.rmSync(f);
  if (fs.existsSync(manifestPath)) fs.rmSync(manifestPath);
};
